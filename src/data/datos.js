// Órdenes de ejemplo para que el panel tenga historial desde el primer uso.
function armarOrdenDemo(boleta, fecha, cliente, region, comuna, entregaId, lineas, estado) {
  const entrega = METODOS_ENTREGA.find((m) => m.id === entregaId);
  const items = lineas.map(([id, cantidad]) => {
    const carta = CARTAS_INICIALES.find((c) => c.id === id);
    const precioUnitario = carta.oferta && carta.precioOferta ? carta.precioOferta : carta.precio;
    return { productoId: id, nombre: carta.nombre, precioUnitario, cantidad, subtotal: precioUnitario * cantidad };
  });
  const subtotal = items.reduce((suma, item) => suma + item.subtotal, 0);
  return {
    id: 'o-demo-' + boleta,
    boleta,
    fecha,
    cliente,
    direccion: { calle: 'Av. Principal', numero: '123', region, comuna, referencias: '' },
    entrega,
    items,
    subtotal,
    total: subtotal + entrega.costo,
    estado,
  };
}

